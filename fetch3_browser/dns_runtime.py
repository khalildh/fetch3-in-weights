"""Execute the exported DNS circuit; the bridge only exchanges its packet bytes."""
import hashlib
import ipaddress
import json
import socket
import time
from pathlib import Path
from urllib.parse import urlsplit

from . import dns as D

WEIGHTS = Path(__file__).parent / "dns_weights"


def load_model():
    for name, expected in json.loads((WEIGHTS / "SHA256.json").read_text()).items():
        if hashlib.sha256((WEIGHTS / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"DNS circuit artifact checksum mismatch: {name}")
    lo, fetch_lo, vocab, lo2 = json.loads((WEIGHTS / "layout.json").read_text())
    lay = D.Layout(lo, fetch_lo, lo2)
    return D.DnsNet(WEIGHTS, lay, vocab), lay


def system_resolver():
    for line in Path("/etc/resolv.conf").read_text().splitlines():
        fields = line.split()
        if len(fields) >= 2 and fields[0] == "nameserver":
            return str(ipaddress.ip_address(fields[1].split("%")[0]))
    raise ValueError("no resolver in /etc/resolv.conf; supply --resolver IP")


def dns_answer(query, address=None, truncated=False):
    """Deterministic test input, not a resolver or a circuit output shortcut."""
    header = query[:2] + (b"\x83\x80" if truncated else b"\x81\x80")
    header += b"\x00\x01" + (b"\x00\x01" if address else b"\x00\x00") + bytes(4)
    packet = header + query[12:]
    if address:
        raw = ipaddress.ip_address(address).packed
        packet += b"\xc0\x0c" + query[-4:] + (30).to_bytes(4, "big") + len(raw).to_bytes(2, "big") + raw
    return packet


def recv_exact(sock, size, deadline):
    data = bytearray()
    while len(data) < size:
        sock.settimeout(max(0.01, deadline-time.monotonic()))
        chunk = sock.recv(size-len(data))
        if not chunk:
            raise OSError("DNS TCP connection closed before complete response")
        data.extend(chunk)
    return bytes(data)


class Resolver:
    def __init__(self, live=False, resolver=None, scenario="normal", replay=None, timeout=5.0):
        self.live, self.resolver, self.scenario, self.replay = live, resolver, scenario, replay
        self.timeout = timeout
        self.records, self.network_exchanges = [], 0

    def exchange(self, query, tcp, qtype):
        transport = "tcp" if tcp else "udp"
        injected = None
        if self.replay is not None:
            if not self.replay:
                raise ValueError("DNS replay exhausted")
            record = self.replay.pop(0)
            if record["query_hex"] != query.hex() or record["transport"] != transport:
                raise ValueError("DNS replay request differs from circuit output")
            self.records.append(record)
            return bytes.fromhex(record["response_hex"]), record["term"]
        if self.live:
            resolver = ipaddress.ip_address(self.resolver or system_resolver())
            fam = socket.AF_INET6 if resolver.version == 6 else socket.AF_INET
            address = (str(resolver), 53)
            with socket.socket(fam, socket.SOCK_STREAM if tcp else socket.SOCK_DGRAM) as sock:
                sock.settimeout(self.timeout)
                sock.connect(address)
                if tcp:
                    sock.sendall(len(query).to_bytes(2,"big") + query)
                    deadline = time.monotonic()+self.timeout
                    size = int.from_bytes(recv_exact(sock,2,deadline),"big")
                    if size > D.PMAXT:
                        raise ValueError("DNS TCP response exceeds circuit tape")
                    wire_response = recv_exact(sock,size,deadline)
                else:
                    sock.send(query)
                    wire_response = sock.recv(D.PMAX+1)
            self.network_exchanges += 1
        else:
            addr = "10.0.0.5" if self.scenario == "private" else (
                "2606:4700:4700::1111" if qtype == 28 else "93.184.216.34")
            wire_response = dns_answer(query, addr)
        response = wire_response
        # Explicit test scenarios: force the circuit to take fallback branches. The
        # follow-up TCP/AAAA query is still generated by the circuit and, in live
        # mode, exchanged with the actual resolver. Normal mode injects nothing.
        if not self.records and qtype == 1 and not tcp:
            if self.scenario == "tcp-retry":
                response, injected = dns_answer(query,truncated=True), "synthetic TC response"
            elif self.scenario == "aaaa-fallback":
                response, injected = dns_answer(query), "synthetic A NODATA response"
        term = D.CUT if len(response) > (D.PMAXT if tcp else D.PMAX) else D.EOF
        response = response[:D.PMAXT if tcp else D.PMAX]
        self.records.append(dict(transport=transport,qtype=qtype,query_hex=query.hex(),
            response_hex=response.hex(),wire_response_hex=wire_response.hex(),term=int(term),
            injected_response=injected))
        return response,int(term)

    def resolve(self, url):
        net,lay = load_model()
        dec = net.decoder()
        responses, tokens = [], []
        spec = D.Spec(lay,net.allow,lambda q:responses.pop(0),lambda q:responses.pop(0))
        queue = [0,7,*lay.call(url)]
        while queue:
            if len(tokens) >= net.TREAL:
                raise ValueError("DNS circuit context limit reached")
            token = queue.pop(0)
            code,fire,notfire = dec.step(token)
            nxt = net.decode_code(code) if fire == 1 else None
            if fire not in (0,1) or (fire == 0 and (code.any() or notfire != net.nb)):
                raise AssertionError("invalid DNS circuit fire/silence")
            tokens.append(int(token))
            if nxt == lay.SEND:
                qtype,query,k = D.query_of(lay,tokens)
                if D.qname_host(query) != urlsplit(url).hostname:
                    raise ValueError("DNS circuit query does not match requested host")
                body,term = self.exchange(query,D.is_tcp(lay,tokens[k]),qtype)
                net.page(dec,list(body)+[term])
                responses.append((list(body),term))
            if spec.feed(token) != nxt:
                raise AssertionError(f"DNS circuit/spec mismatch at position {len(tokens)-1}")
            if nxt is not None:
                queue.insert(0,nxt)
        chosen = D.address_of(lay,tokens)
        if chosen is None:
            reasons = [lay.name(t) for t in tokens if t in (lay.NX,lay.PRIV,lay.BAD,lay.NONE)]
            raise ValueError(f"DNS circuit refused resolution: {reasons}")
        version,raw,_ = chosen
        # This check validates the selected output; it does not choose an address.
        oracle = D.ref_resolve(bytes.fromhex(self.records[-1]['response_hex']),
            bytes.fromhex(self.records[-1]['query_hex']),self.records[-1]['qtype'])
        if oracle != ('ip',raw):
            raise AssertionError("DNS circuit address differs from independent resolver")
        if self.replay:
            raise ValueError("DNS replay has unused exchanges")
        proof = dict(backend="compiled-dns-circuit/numpy-int64",host=urlsplit(url).hostname,
            selected_address=str(ipaddress.ip_address(raw)),address_version=version,
            positions=len(tokens),circuit_matches_spec=True,independent_resolver_matches=True,
            scenario=self.scenario,network_exchanges=self.network_exchanges,
            exchanges=[dict(transport=r['transport'],qtype=r['qtype'],
                query_sha256=hashlib.sha256(bytes.fromhex(r['query_hex'])).hexdigest(),
                injected_response=r.get('injected_response')) for r in self.records],
            token_sha256=hashlib.sha256(json.dumps(tokens,separators=(',',':')).encode()).hexdigest())
        return proof,self.records


def main():
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--url',default='https://example.com')
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument('--live',action='store_true')
    mode.add_argument('--replay',type=Path)
    parser.add_argument('--record',type=Path)
    parser.add_argument('--resolver',help='numeric resolver IP, port 53')
    parser.add_argument('--scenario',choices=['normal','tcp-retry','aaaa-fallback'],default='normal',
        help='fallback scenarios deliberately replace the first A reply; later queries are real in live mode')
    args=parser.parse_args()
    saved=json.loads(args.replay.read_text()) if args.replay else None
    if saved and (saved['url'] != args.url or saved['scenario'] != args.scenario):
        parser.error('--url and --scenario must match the recording')
    resolver=Resolver(live=args.live,resolver=args.resolver,scenario=args.scenario,
        replay=list(saved['exchanges']) if saved else None)
    try:
        proof,records=resolver.resolve(args.url)
    except (OSError,ValueError,AssertionError) as error:
        parser.exit(1,f'DNS: {error}\n')
    if saved and proof['token_sha256'] != saved['proof']['token_sha256']:
        parser.exit(1,'DNS replay token hash differs from recording\n')
    print(json.dumps(proof,indent=2))
    if args.record:
        args.record.parent.mkdir(parents=True,exist_ok=True)
        args.record.write_text(json.dumps(dict(url=args.url,scenario=args.scenario,
            proof=proof,exchanges=records),indent=2)+'\n')


if __name__=='__main__':
    main()
